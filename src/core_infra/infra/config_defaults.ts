import { log_info } from "./global_logger.ts"

/**
 * V16: 集中式默认配置。
 *
 * 将分散在各模块的默认值统一管理，提供单一真相来源。
 */
export interface DefaultConfig {
  /** HTTP 服务器端口 */
  port: number
  /** 工作目录 */
  cwd: string
  /** 最大对话轮次 */
  max_turns: number
  /** 日志级别 */
  log_level: string
  /** 是否详细日志 */
  verbose: boolean
  /** 认证相关 */
  auth: {
    /** 公开路径（无需鉴权） */
    public_paths: string[]
    /** 速率限制最大请求数 */
    rate_limit_max: number
  }
  /** 守护进程相关 */
  daemon: {
    /** 健康检查间隔（毫秒） */
    health_check_interval_ms: number
    /** 计划恢复间隔（毫秒） */
    plan_recovery_interval_ms: number
    /** 是否自动恢复失败计划 */
    auto_recover_plans: boolean
    /** 最大恢复失败次数 */
    max_recovery_failures: number
  }
  /** 会话相关 */
  session: {
    /** 默认最大历史记录 */
    default_max_history: number
  }
  /** Shell 相关 */
  shell: {
    /** 命令执行超时（毫秒） */
    timeout_ms: number
  }
}

/**
 * V16: 全局默认配置常量。
 */
export const DEFAULT_CONFIG: DefaultConfig = {
  port: 3000,
  cwd: process.cwd(),
  max_turns: 50,
  log_level: "info",
  verbose: false,
  auth: {
    public_paths: ["/health", "/health/live", "/health/ready"],
    rate_limit_max: 100,
  },
  daemon: {
    health_check_interval_ms: 5000,
    plan_recovery_interval_ms: 3000,
    auto_recover_plans: true,
    max_recovery_failures: 5,
  },
  session: {
    default_max_history: 50,
  },
  shell: {
    timeout_ms: 30000,
  },
}

/**
 * V16: 获取默认配置的深拷贝。
 */
export function get_default_config(): DefaultConfig {
  return JSON.parse(JSON.stringify(DEFAULT_CONFIG))
}

/**
 * V16: 将用户配置与默认配置深度合并。
 *
 * 用户配置中的值覆盖默认值，未提供的字段使用默认值。
 */
export function apply_config_defaults(user_config: Partial<DefaultConfig>): DefaultConfig {
  log_info("config_defaults_apply")
  const result: DefaultConfig = get_default_config()

  if (user_config.port !== undefined) result.port = user_config.port
  if (user_config.cwd !== undefined) result.cwd = user_config.cwd
  if (user_config.max_turns !== undefined) result.max_turns = user_config.max_turns
  if (user_config.log_level !== undefined) result.log_level = user_config.log_level
  if (user_config.verbose !== undefined) result.verbose = user_config.verbose

  if (user_config.auth) {
    if (user_config.auth.public_paths !== undefined) {
      result.auth.public_paths = [...user_config.auth.public_paths]
    }
    if (user_config.auth.rate_limit_max !== undefined) {
      result.auth.rate_limit_max = user_config.auth.rate_limit_max
    }
  }

  if (user_config.daemon) {
    if (user_config.daemon.health_check_interval_ms !== undefined) {
      result.daemon.health_check_interval_ms = user_config.daemon.health_check_interval_ms
    }
    if (user_config.daemon.plan_recovery_interval_ms !== undefined) {
      result.daemon.plan_recovery_interval_ms = user_config.daemon.plan_recovery_interval_ms
    }
    if (user_config.daemon.auto_recover_plans !== undefined) {
      result.daemon.auto_recover_plans = user_config.daemon.auto_recover_plans
    }
    if (user_config.daemon.max_recovery_failures !== undefined) {
      result.daemon.max_recovery_failures = user_config.daemon.max_recovery_failures
    }
  }

  if (user_config.session) {
    if (user_config.session.default_max_history !== undefined) {
      result.session.default_max_history = user_config.session.default_max_history
    }
  }

  if (user_config.shell) {
    if (user_config.shell.timeout_ms !== undefined) {
      result.shell.timeout_ms = user_config.shell.timeout_ms
    }
  }

  return result
}

/**
 * V16: 将配置对象序列化为 YAML 格式字符串。
 */
export function config_to_yaml(config: DefaultConfig): string {
  const lines: string[] = [
    "# Claude Code Engine Configuration",
    "# Generated by config wizard",
    "",
    `port: ${config.port}`,
    `cwd: ${config.cwd}`,
    `max_turns: ${config.max_turns}`,
    `log_level: ${config.log_level}`,
    `verbose: ${config.verbose}`,
    "",
    "# Auth configuration",
    "auth:",
    `  public_paths:`,
    ...config.auth.public_paths.map((p) => `    - "${p}"`),
    `  rate_limit_max: ${config.auth.rate_limit_max}`,
    "",
    "# Daemon configuration",
    "daemon:",
    `  health_check_interval_ms: ${config.daemon.health_check_interval_ms}`,
    `  plan_recovery_interval_ms: ${config.daemon.plan_recovery_interval_ms}`,
    `  auto_recover_plans: ${config.daemon.auto_recover_plans}`,
    `  max_recovery_failures: ${config.daemon.max_recovery_failures}`,
    "",
    "# Session configuration",
    "session:",
    `  default_max_history: ${config.session.default_max_history}`,
    "",
    "# Shell configuration",
    "shell:",
    `  timeout_ms: ${config.shell.timeout_ms}`,
    "",
  ]
  return lines.join("\n")
}
